#!/usr/bin/env bash
# Write the Homebrew formula and Scoop manifest for a release into a tap
# checkout. Usage: scripts/package-managers.sh v0.2.0 dist/SHA256SUMS <tap-dir>
# Run by the release workflow after the archives are built; the formulas only
# point at the GitHub release assets and pin their SHA-256 sums.
set -euo pipefail
ver="${1:?version}"; sums="${2:?SHA256SUMS}"; tap="${3:?tap dir}"
v="${ver#v}"
base="https://github.com/veridit/huginn/releases/download/${ver}"
sha() { awk -v f="$1" '$2==f {print $1}' "$sums"; }
need() { [ -n "$(sha "$1")" ] || { echo "missing $1 in $sums" >&2; exit 1; }; }
for f in darwin_arm64.tar.gz darwin_amd64.tar.gz linux_arm64.tar.gz linux_amd64.tar.gz windows_amd64.zip windows_arm64.zip; do
  need "huginn_${v}_${f}"
done
mkdir -p "$tap/Formula" "$tap/bucket"

cat > "$tap/Formula/huginn.rb" <<EOF
# Generated by veridit/huginn scripts/package-managers.sh for ${ver}. Do not edit.
class Huginn < Formula
  desc "Git-branch task tracker for people and agents"
  homepage "https://github.com/veridit/huginn"
  license "MPL-2.0"

  on_macos do
    on_arm do
      url "${base}/huginn_${v}_darwin_arm64.tar.gz"
      sha256 "$(sha "huginn_${v}_darwin_arm64.tar.gz")"
    end
    on_intel do
      url "${base}/huginn_${v}_darwin_amd64.tar.gz"
      sha256 "$(sha "huginn_${v}_darwin_amd64.tar.gz")"
    end
  end

  on_linux do
    on_arm do
      url "${base}/huginn_${v}_linux_arm64.tar.gz"
      sha256 "$(sha "huginn_${v}_linux_arm64.tar.gz")"
    end
    on_intel do
      url "${base}/huginn_${v}_linux_amd64.tar.gz"
      sha256 "$(sha "huginn_${v}_linux_amd64.tar.gz")"
    end
  end

  def install
    bin.install "huginn"
  end

  def caveats
    <<~EOS
      Start tracking tasks inside a Git checkout:
        huginn init
      Wire Jcode MCP (keeps backups, idempotent):
        huginn install jcode
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/huginn version")
  end
end
EOF

cat > "$tap/bucket/huginn.json" <<EOF
{
    "version": "${v}",
    "description": "Git-branch task tracker for people and agents",
    "homepage": "https://github.com/veridit/huginn",
    "license": "MPL-2.0",
    "architecture": {
        "64bit": {
            "url": "${base}/huginn_${v}_windows_amd64.zip",
            "hash": "$(sha "huginn_${v}_windows_amd64.zip")",
            "extract_dir": "huginn_${v}_windows_amd64"
        },
        "arm64": {
            "url": "${base}/huginn_${v}_windows_arm64.zip",
            "hash": "$(sha "huginn_${v}_windows_arm64.zip")",
            "extract_dir": "huginn_${v}_windows_arm64"
        }
    },
    "bin": "huginn.exe",
    "checkver": "github",
    "autoupdate": {
        "architecture": {
            "64bit": {
                "url": "https://github.com/veridit/huginn/releases/download/v\$version/huginn_\$version_windows_amd64.zip",
                "extract_dir": "huginn_\$version_windows_amd64"
            },
            "arm64": {
                "url": "https://github.com/veridit/huginn/releases/download/v\$version/huginn_\$version_windows_arm64.zip",
                "extract_dir": "huginn_\$version_windows_arm64"
            }
        },
        "hash": { "url": "https://github.com/veridit/huginn/releases/download/v\$version/SHA256SUMS" }
    }
}
EOF
echo "wrote $tap/Formula/huginn.rb and $tap/bucket/huginn.json for ${ver}"
